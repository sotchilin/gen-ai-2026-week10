-- OT Management System relational schema (PostgreSQL / Supabase)

CREATE TABLE IF NOT EXISTS residents (
    resident_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    room_number TEXT NOT NULL,
    bed_number INTEGER CHECK (bed_number IS NULL OR bed_number >= 0),
    has_dementia BOOLEAN NOT NULL DEFAULT FALSE,
    requires_wheelchair BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'discharged', 'hospitalized')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION prevent_active_resident_bed_conflict()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status <> 'active' OR NEW.bed_number IS NULL THEN
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE'
       AND NEW.room_number = OLD.room_number
       AND NEW.bed_number = OLD.bed_number
       AND NEW.status = OLD.status THEN
        RETURN NEW;
    END IF;

    PERFORM pg_advisory_xact_lock(hashtext(NEW.room_number), NEW.bed_number);

    IF EXISTS (
        SELECT 1
        FROM residents
        WHERE room_number = NEW.room_number
          AND bed_number = NEW.bed_number
          AND status = 'active'
          AND resident_id <> NEW.resident_id
    ) THEN
        RAISE EXCEPTION 'Room %, bed % is already assigned to an active resident',
            NEW.room_number, NEW.bed_number
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS residents_prevent_active_bed_conflict ON residents;
CREATE TRIGGER residents_prevent_active_bed_conflict
    BEFORE INSERT OR UPDATE OF room_number, bed_number, status ON residents
    FOR EACH ROW
    EXECUTE FUNCTION prevent_active_resident_bed_conflict();

CREATE TABLE IF NOT EXISTS clinical_profiles (
    profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id BIGINT NOT NULL REFERENCES residents(resident_id) ON DELETE RESTRICT,
    assessment_date DATE NOT NULL,
    hkbc_score INTEGER CHECK (hkbc_score IS NULL OR hkbc_score >= 0),
    moca_score INTEGER CHECK (moca_score IS NULL OR moca_score BETWEEN 0 AND 30),
    restraint_status TEXT,
    mental_health_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dietary_requirements (
    diet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resident_id BIGINT NOT NULL REFERENCES residents(resident_id) ON DELETE RESTRICT,
    food_texture TEXT NOT NULL DEFAULT 'Normal',
    fluid_consistency TEXT NOT NULL DEFAULT 'Regular',
    food_allergies TEXT,
    adaptive_equipment TEXT,
    effective_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS therapy_groups (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name TEXT NOT NULL,
    group_code TEXT NOT NULL UNIQUE,
    location TEXT NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES therapy_groups(group_id) ON DELETE RESTRICT,
    scheduled_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    therapist TEXT,
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT sessions_valid_time CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS session_enrollments (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions(session_id) ON DELETE RESTRICT,
    resident_id BIGINT NOT NULL REFERENCES residents(resident_id) ON DELETE RESTRICT,
    transfer_type TEXT NOT NULL DEFAULT '無'
        CHECK (transfer_type IN ('落人', 'PT過OT', 'OT過PT', '無')),
    transfer_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (transfer_status IN ('pending', 'in_progress', 'completed')),
    attendance_status TEXT NOT NULL DEFAULT 'scheduled'
        CHECK (attendance_status IN ('scheduled', 'attended', 'absent', 'refused')),
    performance_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT session_enrollments_resident_once UNIQUE (session_id, resident_id)
);

CREATE TABLE IF NOT EXISTS security_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS clinical_profiles_resident_date_idx
    ON clinical_profiles (resident_id, assessment_date DESC);
CREATE INDEX IF NOT EXISTS dietary_requirements_resident_date_idx
    ON dietary_requirements (resident_id, effective_date DESC);
CREATE INDEX IF NOT EXISTS sessions_date_time_idx
    ON sessions (scheduled_date, start_time);
CREATE INDEX IF NOT EXISTS session_enrollments_session_idx
    ON session_enrollments (session_id);
CREATE INDEX IF NOT EXISTS session_enrollments_resident_idx
    ON session_enrollments (resident_id);

